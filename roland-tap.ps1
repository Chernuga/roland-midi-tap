<#
.SYNOPSIS
    Roland MIDI Tap -- capture Roland Piano App recordings as MIDI files.

.DESCRIPTION
    Terminal front-end for an ESP32-S3 that impersonates a Roland Digital
    Piano over USB-MIDI. The phone's Roland Piano App connects to it and
    streams every note; this script receives that stream over WiFi and
    converts it into Standard MIDI Files.

.PARAMETER Command
    menu | setup | config | build | flash | listen | stop | record | convert | verify | open

.EXAMPLE
    .\roland-tap.ps1
    .\roland-tap.ps1 setup
    .\roland-tap.ps1 record
#>
[CmdletBinding()]
param(
    [Parameter(Position = 0)][string]$Command = "menu",
    [switch]$NoPause
)

$ErrorActionPreference = 'Continue'
$Root    = $PSScriptRoot
$Tools   = Join-Path $Root 'tools'
$Firmware= Join-Path $Root 'firmware\RolandTap'
$CfgPath = Join-Path $Root 'config.json'
$StateDir= Join-Path $Root '.state'
$LogPath = Join-Path $StateDir 'capture.log'
$OffPath = Join-Path $StateDir 'offset.txt'
$PidPath = Join-Path $StateDir 'listener.pid'
$OutPath = Join-Path $StateDir 'listener.out'
$TracksPath = Join-Path $Root 'tracks.csv'

$Fqbn = 'esp32:esp32:esp32s3:USBMode=default,CDCOnBoot=default,FlashSize=8M,PartitionScheme=default_8MB'

# ------------------------------------------------------------------ output
function W-Head($text) {
    Write-Host ''
    Write-Host ('=' * 68) -ForegroundColor DarkCyan
    Write-Host "  $text" -ForegroundColor Cyan
    Write-Host ('=' * 68) -ForegroundColor DarkCyan
}
function W-Item($label, $value, $colour = 'Gray') {
    Write-Host ('  {0,-12} {1}' -f $label, $value) -ForegroundColor $colour
}
function W-Ok($t)   { Write-Host "  [OK]   $t" -ForegroundColor Green }
function W-Warn($t) { Write-Host "  [WARN] $t" -ForegroundColor Yellow }
function W-Err($t)  { Write-Host "  [FAIL] $t" -ForegroundColor Red }
function W-Info($t) { Write-Host "  $t" -ForegroundColor Gray }

# ------------------------------------------------------------------ helpers
function Ensure-State {
    if (-not (Test-Path $StateDir)) { New-Item -ItemType Directory -Force -Path $StateDir | Out-Null }
}

function Get-PythonExe {
    $c = Get-Command python -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    return $null
}

function Get-LanIP {
    try {
        $addrs = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction Stop |
                 Where-Object { $_.IPAddress -notlike '127.*' -and $_.IPAddress -notlike '169.254.*' }
        $wifi = $addrs | Where-Object { $_.InterfaceAlias -match 'Wi-?Fi|Wireless' } | Select-Object -First 1
        if ($wifi) { return $wifi.IPAddress }
        if ($addrs) { return ($addrs | Select-Object -First 1).IPAddress }
    } catch { }
    return '127.0.0.1'
}

function Get-ComPort {
    # Only USB-serial bridges are candidates -- skip motherboard/AMT ports.
    $ports = Get-CimInstance Win32_PnPEntity -ErrorAction SilentlyContinue |
             Where-Object { $_.Name -match '\(COM\d+\)' -and
                            $_.Name -match 'CH340|CH341|CH910|CP210|Silicon Labs|USB-SERIAL|USB JTAG|Espressif' }
    if (-not $ports) { return $null }
    $pick = $ports | Select-Object -First 1
    if ($pick.Name -match '\((COM\d+)\)') { return $Matches[1] }
    return $null
}

function Get-ArduinoCli {
    $c = Get-Command arduino-cli -ErrorAction SilentlyContinue
    if ($c) { return $c.Source }
    $local = Join-Path $Root 'tools\arduino-cli.exe'
    if (Test-Path $local) { return $local }
    return $null
}

function Read-Config {
    if (Test-Path $CfgPath) {
        try { return Get-Content $CfgPath -Raw | ConvertFrom-Json } catch { }
    }
    return $null
}

function New-DefaultConfig {
    [pscustomobject]@{
        ssid     = ''
        password = ''
        host     = (Get-LanIP)
        port     = 5005
        comPort  = (Get-ComPort)
        outDir   = (Join-Path $Root 'output')
        arduinoCli = ''
    }
}

function Save-Config($cfg) {
    $cfg | ConvertTo-Json -Depth 5 | Set-Content -Path $CfgPath -Encoding UTF8
}

function Get-Config {
    $cfg = Read-Config
    if (-not $cfg) { $cfg = New-DefaultConfig }
    if (-not $cfg.outDir) { $cfg.outDir = (Join-Path $Root 'output') }
    return $cfg
}

function Write-Secrets($cfg) {
    $h = @(
        '#pragma once',
        '// Generated by roland-tap.ps1 -- do not commit.',
        ('#define WIFI_SSID "{0}"' -f $cfg.ssid),
        ('#define WIFI_PASS "{0}"' -f $cfg.password),
        ('#define PC_HOST   "{0}"' -f $cfg.host),
        ('#define PC_PORT   {0}' -f $cfg.port)
    ) -join "`r`n"
    Set-Content -Path (Join-Path $Firmware 'secrets.h') -Value $h -Encoding ASCII
}

function Test-Listener {
    try {
        $c = Get-NetTCPConnection -LocalPort 5005 -State Listen -ErrorAction Stop
        return [bool]$c
    } catch { return $false }
}

# ------------------------------------------------------------------ commands
function Show-Status {
    $cfg = Get-Config
    W-Head 'Roland MIDI Tap'
    $py = Get-PythonExe
    W-Item 'python'    $(if ($py) { $py } else { 'not found' }) $(if ($py) { 'Gray' } else { 'Red' })
    $cli = Get-ArduinoCli
    W-Item 'arduino-cli' $(if ($cli) { $cli } else { 'not found' }) $(if ($cli) { 'Gray' } else { 'Yellow' })
    W-Item 'board'     $(if ($cfg.comPort) { $cfg.comPort } else { 'not detected' }) $(if ($cfg.comPort) { 'Gray' } else { 'Yellow' })
    W-Item 'PC host'   ('{0}:{1}' -f $cfg.host, $cfg.port)
    W-Item 'wifi ssid' $(if ($cfg.ssid) { $cfg.ssid } else { 'not configured' }) $(if ($cfg.ssid) { 'Gray' } else { 'Yellow' })
    W-Item 'output'    $cfg.outDir
    $lst = Test-Listener
    W-Item 'listener'  $(if ($lst) { 'running on port 5005' } else { 'stopped' }) $(if ($lst) { 'Green' } else { 'Gray' })
    if (Test-Path $LogPath) {
        $mb = [math]::Round((Get-Item $LogPath).Length / 1MB, 2)
        W-Item 'capture log' ('{0} MB' -f $mb)
    }
    if (Test-Path $cfg.outDir) {
        $n = (Get-ChildItem $cfg.outDir -Filter '*.mid' -ErrorAction SilentlyContinue).Count
        W-Item 'midi files' $n
    }
}

function Do-Setup {
    W-Head 'Setup check'
    $ok = $true

    $py = Get-PythonExe
    if ($py) { W-Ok "python: $py" } else { W-Err 'python not found -- install Python 3 and add to PATH'; $ok = $false }

    if ($py) {
        $mods = @('esptool')
        foreach ($m in $mods) {
            $r = & $py -c "import $m" 2>&1
            if ($LASTEXITCODE -eq 0) { W-Ok "python module: $m" }
            else { W-Warn "python module missing: $m  ->  python -m pip install $m" }
        }
    }

    $cli = Get-ArduinoCli
    if ($cli) {
        W-Ok "arduino-cli: $cli"
        $cores = & $cli core list 2>&1
        if ($cores -match 'esp32:esp32') { W-Ok 'esp32 core installed' }
        else { W-Warn 'esp32 core missing -> arduino-cli core install esp32:esp32' }
    } else {
        W-Warn 'arduino-cli not found -- download it into tools\arduino-cli.exe'
    }

    $com = Get-ComPort
    if ($com) { W-Ok "serial port: $com" } else { W-Warn 'no ESP32 COM port detected (is it plugged in?)' }

    $cfg = Get-Config
    if ($cfg.ssid) { W-Ok "wifi configured: $($cfg.ssid)" } else { W-Warn 'wifi not configured -> run: roland-tap.ps1 config' }

    Write-Host ''
    if ($ok) { W-Ok 'setup looks usable' } else { W-Warn 'fix the FAIL items above first' }
}

function Do-Config {
    W-Head 'Configure'
    $cfg = Get-Config

    $ssid = Read-Host ("  WiFi SSID    [{0}]" -f $cfg.ssid)
    if ($ssid) { $cfg.ssid = $ssid }

    $pw = Read-Host ("  WiFi password [{0}]" -f $(if ($cfg.password) { '(set)' } else { '(empty)' }))
    if ($pw) { $cfg.password = $pw }

    $defHost = Get-LanIP
    $hostIn = Read-Host ("  PC LAN IP    [{0}]" -f $defHost)
    $cfg.host = if ($hostIn) { $hostIn } else { $defHost }

    $portIn = Read-Host ("  TCP port     [{0}]" -f $cfg.port)
    if ($portIn) { $cfg.port = [int]$portIn }

    $com = Get-ComPort
    $comIn = Read-Host ("  COM port     [{0}]" -f $(if ($cfg.comPort) { $cfg.comPort } elseif ($com) { $com } else { 'auto' }))
    $cfg.comPort = if ($comIn) { $comIn } elseif ($com) { $com } else { $cfg.comPort }

    $outIn = Read-Host ("  output dir   [{0}]" -f $cfg.outDir)
    if ($outIn) { $cfg.outDir = $outIn }

    Save-Config $cfg
    if (-not (Test-Path $cfg.outDir)) { New-Item -ItemType Directory -Force -Path $cfg.outDir | Out-Null }
    W-Ok 'saved config.json'
    W-Info 'next: build firmware (option 3), then flash (option 4)'
}

function Do-Build {
    W-Head 'Build firmware'
    $cfg = Get-Config
    $cli = Get-ArduinoCli
    if (-not $cli) { W-Err 'arduino-cli not found'; return }
    if (-not $cfg.ssid) { W-Err 'wifi not configured -- run: roland-tap.ps1 config'; return }

    Write-Secrets $cfg
    W-Ok "secrets.h written (ssid=$($cfg.ssid), host=$($cfg.host):$($cfg.port))"

    $out = Join-Path $StateDir 'build'
    if (-not (Test-Path $out)) { New-Item -ItemType Directory -Force -Path $out | Out-Null }
    W-Info "compiling for $Fqbn"
    & $cli compile --fqbn $Fqbn --output-dir $out $Firmware 2>&1 | ForEach-Object { Write-Host "    $_" }
    if ($LASTEXITCODE -eq 0) { W-Ok 'build succeeded' } else { W-Err 'build failed' }
}

function Do-Flash {
    W-Head 'Flash firmware'
    $cfg = Get-Config
    $cli = Get-ArduinoCli
    if (-not $cli) { W-Err 'arduino-cli not found'; return }
    if (-not $cfg.comPort) { $cfg.comPort = Get-ComPort }
    if (-not $cfg.comPort) { W-Err 'no COM port detected'; return }

    $out = Join-Path $StateDir 'build'
    if (-not (Test-Path $out)) { W-Err 'no build output -- run build first'; return }

    W-Info "flashing to $($cfg.comPort)"
    & $cli upload -p $cfg.comPort --fqbn $Fqbn --input-dir $out 2>&1 | ForEach-Object { Write-Host "    $_" }
    if ($LASTEXITCODE -eq 0) {
        W-Ok 'flash complete'
        W-Info 'now move the ESP32 to the phone: native USB port -> USB-C OTG adapter'
        W-Info 'and start the listener (option 5) before playing tracks'
    } else { W-Err 'flash failed' }
}

function Do-Listen {
    W-Head 'Start listener'
    if (Test-Listener) { W-Warn 'already listening on 5005'; return }
    $py = Get-PythonExe
    if (-not $py) { W-Err 'python not found'; return }
    Ensure-State

    $script = Join-Path $Tools 'tcplisten.py'
    if (-not (Test-Path $script)) { W-Err "missing $script"; return }

    $args = @($script, '--log', $LogPath, '--port', '5005')
    $p = Start-Process -FilePath $py -ArgumentList $args -PassThru -WindowStyle Hidden `
            -RedirectStandardOutput $OutPath -RedirectStandardError (Join-Path $StateDir 'listener.err')
    Set-Content -Path $PidPath -Value $p.Id -Encoding ASCII
    Start-Sleep -Seconds 2
    if (Test-Listener) {
        W-Ok "listener started (pid $($p.Id)), logging to .state\capture.log"
        W-Info 'waiting for the ESP32 to connect...'
    } else {
        W-Err 'listener did not bind -- is another process using 5005?'
    }
}

function Do-Stop {
    W-Head 'Stop listener'
    if (Test-Path $PidPath) {
        $pidVal = (Get-Content $PidPath -Raw).Trim()
        try { Stop-Process -Id ([int]$pidVal) -Force -ErrorAction Stop; W-Ok "stopped pid $pidVal" }
        catch { W-Warn "could not stop pid $pidVal" }
        Remove-Item $PidPath -Force -ErrorAction SilentlyContinue
    } else {
        W-Warn 'no listener pid recorded'
    }
}

function Count-Rx {
    if (-not (Test-Path $LogPath)) { return 0 }
    return (Select-String -Path $LogPath -Pattern 'RX ' -AllMatches -ErrorAction SilentlyContinue).Count
}

function Do-Record {
    W-Head 'Record tracks'
    $cfg = Get-Config
    $py = Get-PythonExe
    if (-not $py) { W-Err 'python not found'; return }
    if (-not (Test-Listener)) { W-Err 'listener is not running -- start it first (option 5)'; return }
    if (-not (Test-Path $cfg.outDir)) { New-Item -ItemType Directory -Force -Path $cfg.outDir | Out-Null }
    Ensure-State

    if (-not (Test-Path $TracksPath)) {
        $sample = @(
            '# num,title,date,duration',
            '# one row per recording, in the order you will play them',
            '1,My Song,19/07/2026,01:20',
            '2,Another,12/07/2026,02:02'
        )
        $sample | Set-Content -Path $TracksPath -Encoding UTF8
        W-Warn "created a template: $TracksPath"
        W-Info 'fill it in (num,title,date,duration) and run record again'
        return
    }

    $rows = @()
    foreach ($line in Get-Content $TracksPath) {
        $t = $line.Trim()
        if (-not $t -or $t.StartsWith('#')) { continue }
        $p = $t -split ','
        if ($p.Count -lt 4) { continue }
        $rows += [pscustomobject]@{
            Num = [int]$p[0].Trim(); Title = $p[1].Trim()
            Date = $p[2].Trim(); Dur = $p[3].Trim()
        }
    }
    if (-not $rows) { W-Err 'tracks.csv has no usable rows'; return }

    $offset = 0
    if (Test-Path $OffPath) { $offset = [int64](Get-Content $OffPath -Raw).Trim() }
    if ($offset -eq 0) {
        $offset = if (Test-Path $LogPath) { (Get-Item $LogPath).Length } else { 0 }
        Set-Content -Path $OffPath -Value $offset -Encoding ASCII
    }
    W-Info ("{0} track(s) defined, output -> {1}" -f $rows.Count, $cfg.outDir)
    Write-Host ''

    $done = 0
    foreach ($r in $rows) {
        $dp = $r.Dur -split ':'
        $expect = [int]$dp[0] * 60 + [int]$dp[1]
        $safe = $r.Title
        foreach ($ch in [IO.Path]::GetInvalidFileNameChars() + ' ') { $safe = $safe.Replace($ch, '_') }
        if ($safe.Length -gt 40) { $safe = $safe.Substring(0, 40) }
        $name = '{0:D2}_{1}_{2}_{3}s.mid' -f $r.Num, $safe, ($r.Date -replace '/', '-'), $expect
        $target = Join-Path $cfg.outDir $name
        if (Test-Path $target) { W-Info "skip (exists): $name"; continue }

        Write-Host ''
        Write-Host ("  NEXT: #{0}  '{1}'  {2}  {3}" -f $r.Num, $r.Title, $r.Date, $r.Dur) -ForegroundColor Cyan
        Write-Host '  Play it in the Roland app, then press Enter here (Q to stop).' -ForegroundColor DarkGray
        $ans = Read-Host '  '
        if ($ans -match '^[qQ]') { break }

        $res = & $py (Join-Path $Tools 'seg2mid.py') $LogPath $offset $target "$($r.Title) $($r.Date)" 2>&1
        if ($res -match '^OK events=(\d+) span=([\d.]+)s bytes=(\d+)') {
            $ev = [int]$Matches[1]; $span = [double]$Matches[2]; $by = [int]$Matches[3]
            Set-Content -Path $OffPath -Value (Get-Item $LogPath).Length -Encoding ASCII
            & $py (Join-Path $Tools 'trim.py') $target | Out-Null
            $d = [math]::Round($span - $expect, 1)
            $tag = if ([math]::Abs($d) -le 12) { 'OK' } else { 'CHECK' }
            $col = if ($tag -eq 'OK') { 'Green' } else { 'Yellow' }
            Write-Host ("  [{0}] {1}  events={2}  span={3}s  expected={4}s  delta={5}" -f `
                        $tag, $name, $ev, $span, $expect, $d) -ForegroundColor $col
            $done++
        } else {
            Write-Host "  [FAIL] no MIDI captured: $res" -ForegroundColor Red
            Remove-Item $target -Force -ErrorAction SilentlyContinue
        }
    }

    Write-Host ''
    W-Ok ("recorded {0} track(s)" -f $done)
    W-Info 'run: roland-tap.ps1 verify'
}

function Do-Convert {
    W-Head 'Convert capture log'
    $cfg = Get-Config
    $py = Get-PythonExe
    if (-not $py) { W-Err 'python not found'; return }
    if (-not (Test-Path $LogPath)) { W-Err 'no capture log yet'; return }

    $mode = Read-Host '  [1] whole log into one file   [2] split on silence gaps  (1)'
    if (-not $mode) { $mode = '1' }
    $out = Read-Host ("  output file [{0}]" -f (Join-Path $cfg.outDir 'capture.mid'))
    if (-not $out) { $out = Join-Path $cfg.outDir 'capture.mid' }

    if ($mode -eq '2') {
        & $py (Join-Path $Tools 'log2mid.py') $LogPath $out --split-gap 4 2>&1 | ForEach-Object { Write-Host "    $_" }
    } else {
        & $py (Join-Path $Tools 'log2mid.py') $LogPath $out 2>&1 | ForEach-Object { Write-Host "    $_" }
    }
}

function Do-Verify {
    W-Head 'Verify + manifest'
    $cfg = Get-Config
    $py = Get-PythonExe
    if (-not $py) { W-Err 'python not found'; return }
    if (-not (Test-Path $cfg.outDir)) { W-Err 'output dir missing'; return }

    & $py (Join-Path $Tools 'verify.py') $cfg.outDir 2>&1 | ForEach-Object { Write-Host "    $_" }
    Write-Host ''
    & $py (Join-Path $Tools 'manifest.py') $cfg.outDir 2>&1 | Select-Object -Last 4 | ForEach-Object { Write-Host "    $_" }
}

function Do-Open {
    $cfg = Get-Config
    if (Test-Path $cfg.outDir) { Start-Process explorer.exe $cfg.outDir }
    else { W-Warn "output dir does not exist: $($cfg.outDir)" }
}

# ------------------------------------------------------------------ menu
function Show-Menu {
    while ($true) {
        Show-Status
        Write-Host ''
        Write-Host '  1) Setup check          5) Start listener' -ForegroundColor White
        Write-Host '  2) Configure            6) Record tracks' -ForegroundColor White
        Write-Host '  3) Build firmware       7) Convert log -> MIDI' -ForegroundColor White
        Write-Host '  4) Flash firmware       8) Verify + manifest' -ForegroundColor White
        Write-Host '                          9) Open output folder' -ForegroundColor White
        Write-Host '  s) Stop listener        0) Quit' -ForegroundColor DarkGray
        Write-Host ''
        $c = Read-Host '  choice'
        switch ($c) {
            '1' { Do-Setup }
            '2' { Do-Config }
            '3' { Do-Build }
            '4' { Do-Flash }
            '5' { Do-Listen }
            '6' { Do-Record }
            '7' { Do-Convert }
            '8' { Do-Verify }
            '9' { Do-Open }
            's' { Do-Stop }
            '0' { return }
            default { W-Warn "unknown choice: $c" }
        }
        Write-Host ''
        if (-not $NoPause) { Read-Host '  press Enter to continue' | Out-Null }
    }
}

switch ($Command.ToLower()) {
    'setup'   { Do-Setup }
    'config'  { Do-Config }
    'build'   { Do-Build }
    'flash'   { Do-Flash }
    'listen'  { Do-Listen }
    'stop'    { Do-Stop }
    'record'  { Do-Record }
    'convert' { Do-Convert }
    'verify'  { Do-Verify }
    'open'    { Do-Open }
    'status'  { Show-Status }
    default   { Show-Menu }
}
